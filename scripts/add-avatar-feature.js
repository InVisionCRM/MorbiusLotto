#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

const ROOT = process.cwd();
const DB_PATH = path.join(ROOT, 'scripts', 'avatar-feature-registry.db.json');
const GENERATED_TS_PATH = path.join(ROOT, 'lib', 'avatar-feature-registry.generated.ts');

const ALLOWED_CATEGORIES = new Set(['mouth', 'nose', 'hair']);
const ALLOWED_ANCHORS = new Set(['center', 'top-left']);

function fail(msg) {
  console.error(`avatar-feature:add error: ${msg}`);
  process.exit(1);
}

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (!token.startsWith('--')) continue;
    const key = token.slice(2);
    const next = argv[i + 1];
    if (!next || next.startsWith('--')) {
      out[key] = 'true';
      continue;
    }
    out[key] = next;
    i += 1;
  }
  return out;
}

function parseDim(value, fallback) {
  const n = Number.parseFloat(String(value ?? ''));
  return Number.isFinite(n) && n > 0 ? n : fallback;
}

function readSvgFile(svgPath) {
  const raw = fs.readFileSync(svgPath, 'utf8');
  const m = raw.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/i);
  if (!m) fail(`File is not a valid svg: ${svgPath}`);
  const svgTag = raw.match(/<svg\b([^>]*)>/i)?.[1] ?? '';
  const vb = svgTag.match(/viewBox\s*=\s*["']([^"']+)["']/i)?.[1] ?? '';
  const widthAttr = svgTag.match(/width\s*=\s*["']([^"']+)["']/i)?.[1] ?? '';
  const heightAttr = svgTag.match(/height\s*=\s*["']([^"']+)["']/i)?.[1] ?? '';

  let vbWidth = 400;
  let vbHeight = 600;
  if (vb) {
    const parts = vb.split(/[\s,]+/).map(Number).filter((n) => Number.isFinite(n));
    if (parts.length === 4) {
      vbWidth = parts[2] > 0 ? parts[2] : vbWidth;
      vbHeight = parts[3] > 0 ? parts[3] : vbHeight;
    }
  } else {
    vbWidth = parseDim(widthAttr, vbWidth);
    vbHeight = parseDim(heightAttr, vbHeight);
  }

  return {
    innerMarkup: m[1].trim(),
    viewBoxWidth: vbWidth,
    viewBoxHeight: vbHeight,
  };
}

function expandUserPath(inputPath) {
  if (!inputPath) return inputPath;
  if (inputPath === '~') return process.env.HOME || inputPath;
  if (inputPath.startsWith('~/')) {
    const home = process.env.HOME;
    if (!home) return inputPath;
    return path.join(home, inputPath.slice(2));
  }
  return inputPath;
}

function escapeTemplateLiteral(raw) {
  return String(raw).replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

function readDb() {
  if (!fs.existsSync(DB_PATH)) return [];
  try {
    const raw = fs.readFileSync(DB_PATH, 'utf8');
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

function writeDb(entries) {
  fs.writeFileSync(DB_PATH, `${JSON.stringify(entries, null, 2)}\n`, 'utf8');
}

function emitGeneratedTs(entries) {
  const lines = [];
  lines.push("import type { AvatarFeatureDefinition } from './avatar-feature-registry';");
  lines.push('');
  lines.push('/** Auto-generated by scripts/add-avatar-feature.js. */');
  lines.push('export const GENERATED_AVATAR_FEATURES: AvatarFeatureDefinition[] = [');
  for (const f of entries) {
    const notesLine = f.notes ? `,\n    notes: \`${escapeTemplateLiteral(f.notes)}\`` : '';
    lines.push('  {');
    lines.push(`    id: '${f.id}',`);
    lines.push(`    category: '${f.category}',`);
    lines.push(`    sourceViewBox: { width: ${f.sourceViewBox.width}, height: ${f.sourceViewBox.height} },`);
    lines.push(`    svgMarkup: \`${escapeTemplateLiteral(f.svgMarkup)}\`,`);
    lines.push('    placement: {');
    lines.push(`      x: ${f.placement.x},`);
    lines.push(`      y: ${f.placement.y},`);
    lines.push(`      scale: ${f.placement.scale},`);
    lines.push(`      rotation: ${f.placement.rotation},`);
    lines.push(`      zIndex: ${f.placement.zIndex},`);
    lines.push(`      anchor: '${f.placement.anchor}',`);
    lines.push(`    }${notesLine}`);
    lines.push('  },');
  }
  lines.push('];');
  lines.push('');
  fs.writeFileSync(GENERATED_TS_PATH, lines.join('\n'), 'utf8');
}

function main() {
  const args = parseArgs(process.argv.slice(2));

  const category = String(args.category ?? '').trim();
  const id = String(args.id ?? '').trim();
  const svgArgPath = String(args.svg ?? '').trim();

  if (!ALLOWED_CATEGORIES.has(category)) {
    fail('Missing/invalid --category. Use mouth | nose | hair');
  }
  if (!id) fail('Missing --id');
  if (!/^[a-z0-9_:-]+$/i.test(id)) {
    fail('Invalid --id. Use letters/numbers/underscore/dash/colon.');
  }
  if (!svgArgPath) fail('Missing --svg path');
  if (svgArgPath.includes('/absolute/path/to/feature.svg')) {
    fail('Replace placeholder path "/absolute/path/to/feature.svg" with your real SVG file path.');
  }

  const expandedSvgPath = expandUserPath(svgArgPath);
  const svgPath = path.isAbsolute(expandedSvgPath) ? expandedSvgPath : path.join(ROOT, expandedSvgPath);
  if (!fs.existsSync(svgPath)) fail(`SVG file not found: ${svgPath}`);

  const parsedSvg = readSvgFile(svgPath);

  const anchor = String(args.anchor ?? 'center').trim();
  if (!ALLOWED_ANCHORS.has(anchor)) {
    fail('Invalid --anchor. Use center | top-left');
  }

  const entry = {
    id,
    category,
    sourceViewBox: {
      width: parseDim(args.sourceWidth, parsedSvg.viewBoxWidth),
      height: parseDim(args.sourceHeight, parsedSvg.viewBoxHeight),
    },
    svgMarkup: parsedSvg.innerMarkup,
    placement: {
      x: Number.parseFloat(String(args.x ?? '200')),
      y: Number.parseFloat(String(args.y ?? '300')),
      scale: Number.parseFloat(String(args.scale ?? '1')),
      rotation: Number.parseFloat(String(args.rotation ?? '0')),
      zIndex: Number.parseInt(String(args.zIndex ?? '10'), 10),
      anchor,
    },
    notes: args.notes ? String(args.notes) : undefined,
  };

  if (!Number.isFinite(entry.placement.x)) fail('Invalid --x');
  if (!Number.isFinite(entry.placement.y)) fail('Invalid --y');
  if (!Number.isFinite(entry.placement.scale) || entry.placement.scale <= 0) fail('Invalid --scale (> 0)');
  if (!Number.isFinite(entry.placement.rotation)) fail('Invalid --rotation');
  if (!Number.isFinite(entry.placement.zIndex)) fail('Invalid --zIndex');

  const db = readDb();
  const next = db.filter((f) => !(f.id === id && f.category === category));
  next.push(entry);
  next.sort((a, b) => {
    if (a.category !== b.category) return a.category.localeCompare(b.category);
    return a.id.localeCompare(b.id);
  });

  writeDb(next);
  emitGeneratedTs(next);

  console.log(`Added/updated avatar feature: ${category}/${id}`);
  console.log(`Source SVG: ${svgPath}`);
  console.log(`Generated: ${path.relative(ROOT, GENERATED_TS_PATH)}`);
}

main();
